#!/usr/bin/env python3
"""Ki5 handler scanner: turn recognised OnPlayerUpdate handlers into data.

Usage: ki5scan.py WORKSHOP_DIR MODLIST [-o ki5table.lua]

The table holds facts only: handler id, name, kind, vehicle-type filters and
on-foot effect. The Lua dispatcher decides what to call; it never parses code.
"""

import argparse
import os
import re
import sys

ADD = re.compile(r"Events\.OnPlayerUpdate\.Add\(\s*([A-Za-z_][\w.]*)\s*\)")
FUNC = re.compile(r"^[ \t]*function\s+([A-Za-z_][\w.]*)\s*\(", re.M)  # [ \t]: \s* crossed blank lines, one line early
WORDS = re.compile(r"[A-Za-z_]\w*|\S")
OPENERS = {"function", "if", "for", "while", "do"}
TYPE = re.compile(
    r"string\.find\s*\(\s*[^,()]*getScriptName\s*\(\s*\)\s*,\s*\"([^\"]+)\"")


def block_end(text, start):
    """Index just past the `end` matching the block that starts at `start`."""
    depth = 1
    for m in WORDS.finditer(text, start):
        w = m.group(0)
        if w in OPENERS:
            depth += 1
        elif w == "end":
            depth -= 1
            if depth == 0:
                return m.end()
    return len(text)


def function_body(text, name):
    for m in FUNC.finditer(text):
        if m.group(1) != name:
            continue
        begin = m.end() - 1  # at '('
        depth = 0
        close = begin
        for i in range(begin, len(text)):
            c = text[i]
            if c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
                if depth == 0:
                    close = i + 1
                    break
        end = block_end(text, close)
        return text[begin:end], text.count("\n", 0, m.start()) + 1, text.count("\n", 0, end) + 1
    return None, 0, 0


def early_vehicle_return(body):
    """True when the body bails out before doing work if there is no vehicle."""
    for m in re.finditer(r"\bif\b", body):
        end = block_end(body, m.end())
        chunk = body[m.end():end]
        if "return" not in chunk:
            continue
        guard = chunk.split("return", 1)[0].lower()
        if "vehicle" in guard or "getvehiclename" in guard or "string.find" in guard:
            return True
    return False


def classify(body):
    if "getvehicle" not in body.lower():
        return "unchecked", []
    types = sorted(set(TYPE.findall(body)))
    if early_vehicle_return(body):
        return "sync", types
    return "every", types


def mod_info(directory):
    path = os.path.join(directory, "mod.info")
    info = {}
    try:
        with open(path, errors="replace") as f:
            for line in f:
                k, sep, v = line.strip().partition("=")
                if sep and not line.lstrip().startswith("#"):
                    info.setdefault(k.strip(), v.strip())
    except OSError:
        pass
    return info


def active_ids(path):
    try:
        text = open(path, errors="replace").read()
    except OSError:
        return set()
    return set(re.findall(r"mod\s*=\s*([^,\s}]+)", text))


def mod_dirs(root, active):
    for dirpath, dirnames, filenames in os.walk(root):
        if "mod.info" not in filenames:
            continue
        info = mod_info(dirpath)
        mid = info.get("id", "")
        parent = os.path.basename(os.path.dirname(dirpath))
        if mid in active or parent in active:
            yield mid or parent, dirpath
        dirnames[:] = [d for d in dirnames if d not in ("media",)]


def lua_files(root):
    for dirpath, _, filenames in os.walk(root):
        for name in filenames:
            if name.endswith(".lua"):
                yield os.path.join(dirpath, name)


def scan(root, active):
    rows = []
    for mid, directory in mod_dirs(root, active):
        for path in lua_files(directory):
            try:
                text = open(path, errors="replace").read()
            except OSError:
                continue
            rel = os.path.relpath(path, directory).replace(os.sep, "/")
            for m in ADD.finditer(text):
                name = m.group(1)
                body, line, last = function_body(text, name)
                if body is None:
                    continue
                kind, types = classify(body)
                on_foot = "none" if kind == "sync" else "unchecked"
                rows.append({"id": "%s:%s:%d" % (mid, rel, line),
                             "name": name, "kind": kind, "types": types,
                             "onFoot": on_foot, "last": last})
    # one mod id in two workshop items gives the same id twice
    rows = sorted({r["id"]: r for r in rows}.values(), key=lambda r: r["id"])
    return rows


def quote(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


def table_text(rows):
    out = ["-- Generated by tools/ki5scan.py. Facts, not code.",
           "-- Re-run after a KI5 mod update.", "if not PZButter then return end",
           "PZButter.Ki5Table = {"]
    for r in rows:
        types = "{" + ", ".join(quote(t) for t in r["types"]) + "}"
        # the game's census line is the closure's first instruction (getFirstLineOfClosure: Prototype.lines[0]),
        # a line inside the function, not the `function` line: the dispatcher matches id's line .. last
        out.append('    {id=%s, name=%s, kind=%s, types=%s, onFoot=%s, last=%d},' % (
            quote(r["id"]), quote(r["name"]), quote(r["kind"]), types,
            quote(r["onFoot"]), r.get("last", int(r["id"].rsplit(":", 1)[1]))))
    out.append("}")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("workshop")
    ap.add_argument("modlist")
    ap.add_argument("-o", "--out", default=None)
    args = ap.parse_args(argv)
    rows = scan(args.workshop, active_ids(args.modlist))
    text = table_text(rows)
    if args.out:
        with open(args.out, "w") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    print("ki5scan: %d handler(s)" % len(rows), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
